// Straight from `palettes.ts`, not the `@/core/theme` barrel: that barrel pulls in React Native
// (ThemeProvider), which Vitest cannot parse (Flow syntax) — this module stays plain-TS testable.
import { THEME_NAMES, type ThemeName } from '@/core/theme/palettes'

/** What the user picked in Settings → Appearance → App icon. */
export type AppIconPreference = 'matchTheme' | 'original' | ThemeName

export const APP_ICON_PREFERENCES: readonly AppIconPreference[] = ['matchTheme', 'original', ...THEME_NAMES]

export function isAppIconPreference(value: unknown): value is AppIconPreference {
  return typeof value === 'string' && (APP_ICON_PREFERENCES as readonly string[]).includes(value)
}

/**
 * Native alternate-icon name for each theme, from `app.config.ts`'s `expo-alternate-app-icons`
 * plugin config (PascalCase); the PNGs are generated by `scripts/icons.mts`.
 */
const ICON_NAMES: Record<ThemeName, string> = {
  dark: 'Dark',
  light: 'Light',
  dracula: 'Dracula',
  mocha: 'Mocha',
  latte: 'Latte',
}

/**
 * The native icon name a preference resolves to, given the currently resolved theme; `null` means
 * the default icon ("Original"), passed to `resetAppIcon`/`setAlternateAppIcon(null)`.
 */
export function resolveAppIconName(preference: AppIconPreference, resolvedTheme: ThemeName): string | null {
  if (preference === 'original') return null
  if (preference === 'matchTheme') return ICON_NAMES[resolvedTheme]
  return ICON_NAMES[preference]
}

export type IconApplyInput = {
  /** Both saved preferences (theme and app icon) have been read; before that they are defaults. */
  restored: boolean
  preference: AppIconPreference
  resolvedTheme: ThemeName
  /** The icon the system shows now (`getAppIconName()`), `null` for the default icon. */
  current: string | null
  /** The icon this launch already asked for, `undefined` when none. */
  requested: string | null | undefined
}

/**
 * The icon to ask the system for, `undefined` when there is nothing to do. iOS shows an alert on
 * every change, so nothing is applied from defaults (before the preferences are restored), to the
 * icon already showing, or twice to the same icon in one launch (#345).
 */
export function iconToApply(input: IconApplyInput): string | null | undefined {
  if (!input.restored) return undefined
  const target = resolveAppIconName(input.preference, input.resolvedTheme)
  if (target === input.current || target === input.requested) return undefined
  return target
}
