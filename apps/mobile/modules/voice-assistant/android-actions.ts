function escapeXml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, "\\'")
}

/** Activity the App Actions open (in the module's manifest): it forwards the link to the enabled icon. */
export const ASSISTANT_LINK_ACTIVITY = 'expo.modules.voiceassistant.AssistantLinkActivity'

/** `res/xml/shortcuts.xml`: the built-in message intent and the custom intents. */
export function shortcutsXml(packageName: string): string {
  const intent = (body: string) =>
    [
      '    <intent',
      '        android:action="android.intent.action.VIEW"',
      `        android:targetPackage="${packageName}"`,
      `        android:targetClass="${ASSISTANT_LINK_ACTIVITY}">`,
      body,
      '    </intent>',
    ].join('\n')
  const message = [
    '  <capability android:name="actions.intent.CREATE_MESSAGE">',
    intent(
      [
        '      <url-template android:value="remoteharness://assistant/reply{?text,session}" />',
        '      <parameter android:name="message.text" android:key="text" />',
        '      <parameter android:name="message.recipient.name" android:key="session" />',
      ].join('\n'),
    ),
    '  </capability>',
  ].join('\n')
  const custom = Object.entries(CUSTOM_INTENTS).map(([array, action]) =>
    [
      `  <capability android:name="${action.name}" app:queryPatterns="@array/${array}">`,
      intent(`      <url-template android:value="${escapeXml(action.link)}" />`),
      '  </capability>',
    ].join('\n'),
  )
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by app.config.ts from modules/voice-assistant/android-actions.ts. -->',
    '<shortcuts xmlns:android="http://schemas.android.com/apk/res/android"',
    '    xmlns:app="http://schemas.android.com/apk/res-auto">',
    message,
    ...custom,
    '</shortcuts>',
    '',
  ].join('\n')
}

/** `res/<folder>/assistant_queries.xml`: one string array of query patterns per custom intent. */
export function queryArraysXml(language: keyof Patterns): string {
  const arrays = Object.entries(CUSTOM_INTENTS).map(([array, action]) =>
    [
      `  <string-array name="${array}">`,
      ...action.patterns[language].map((pattern) => `    <item>${escapeXml(pattern)}</item>`),
      '  </string-array>',
    ].join('\n'),
  )
  return ['<?xml version="1.0" encoding="utf-8"?>', '<resources>', ...arrays, '</resources>', ''].join('\n')
}
